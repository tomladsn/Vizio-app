// ── Helpers ───────────────────────────────────────────────────────────────────
function uid() { return Math.random().toString(36).slice(2, 9) }

function defaultStep(type) {
  const def = STEP_TYPES[type]
  return {
    id: uid(),
    type,
    title: def.label,
    command:      def.defaultCommand ?? '',
    model:        'base',
    wordsPerLine: '2',
    outputFormat: 'srt',
    prompt:       '',
    sourceVideo:  '{original}',
    fontsize:     '22',
    fontcolor:    'white',
  }
}

function stepColor(type) { return STEP_TYPES[type]?.color ?? '#888' }
function stepIcon(type)  { return STEP_TYPES[type]?.icon  ?? '⚙' }
function stepLabel(type) { return STEP_TYPES[type]?.label ?? type }

// ── Main Page ─────────────────────────────────────────────────────────────────
export default function NodePage({ project, settingsStore, onRunPipeline }) {
  const [pipelines, setPipelines]         = useState(() => loadPipelines())
  const [activePipelineId, setActive]     = useState(pipelines[0]?.id ?? null)
  const [selectedStepId, setSelectedStep] = useState(null)
  const [showTemplates, setShowTemplates] = useState(false)
  const [runState, setRunState]           = useState(null) // { status, stepId, log[] }
  const [inputFile, setInputFile]         = useState(null)
  const dragStep = useRef(null)
  const dragOver = useRef(null)

  const activePipeline = pipelines.find(p => p.id === activePipelineId)
  const selectedStep   = activePipeline?.steps.find(s => s.id === selectedStepId)

  // ── Persistence ───────────────────────────────────────────────────────────
  function loadPipelines() {
    try {
      const raw = localStorage.getItem('vizio_pipelines')
      return raw ? JSON.parse(raw) : []
    } catch { return [] }
  }

  function savePipelines(updated) {
    setPipelines(updated)
    try { localStorage.setItem('vizio_pipelines', JSON.stringify(updated)) } catch {}
  }

  // ── Pipeline CRUD ─────────────────────────────────────────────────────────
  function createFromTemplate(template) {
    const p = {
      id: uid(),
      name: template.id === 'blank' ? 'Untitled Pipeline' : template.name,
      description: template.description,
      steps: template.steps.map(s => ({ ...s, id: uid() })),
      createdAt: Date.now(),
    }
    savePipelines([...pipelines, p])
    setActive(p.id)
    setShowTemplates(false)
  }

  function deletePipeline(id) {
    const updated = pipelines.filter(p => p.id !== id)
    savePipelines(updated)
    setActive(updated[0]?.id ?? null)
  }

  function renamePipeline(id, name) {
    savePipelines(pipelines.map(p => p.id === id ? { ...p, name } : p))
  }

  function updatePipeline(updated) {
    savePipelines(pipelines.map(p => p.id === updated.id ? updated : p))
  }

  // ── Step CRUD ─────────────────────────────────────────────────────────────
  function addStep(type) {
    if (!activePipeline) return
    const step = defaultStep(type)
    updatePipeline({ ...activePipeline, steps: [...activePipeline.steps, step] })
    setSelectedStep(step.id)
  }

  function removeStep(stepId) {
    if (!activePipeline) return
    updatePipeline({ ...activePipeline, steps: activePipeline.steps.filter(s => s.id !== stepId) })
    if (selectedStepId === stepId) setSelectedStep(null)
  }

  function updateStep(stepId, patch) {
    if (!activePipeline) return
    updatePipeline({
      ...activePipeline,
      steps: activePipeline.steps.map(s => s.id === stepId ? { ...s, ...patch } : s),
    })
  }

  // ── Drag reorder ──────────────────────────────────────────────────────────
  function onDragStart(e, idx) { dragStep.current = idx }
  function onDragEnter(e, idx) { dragOver.current = idx }
  function onDragEnd() {
    if (!activePipeline) return
    const steps = [...activePipeline.steps]
    const from  = dragStep.current
    const to    = dragOver.current
    if (from === null || to === null || from === to) return
    const [moved] = steps.splice(from, 1)
    steps.splice(to, 0, moved)
    updatePipeline({ ...activePipeline, steps })
    dragStep.current = null
    dragOver.current = null
  }

  // ── Pick input file ───────────────────────────────────────────────────────
  async function pickInputFile() {
    const path = await window.electron?.project?.choosePath?.()
    if (path) setInputFile(path)
  }

  // ── Run pipeline ──────────────────────────────────────────────────────────
  async function runPipeline() {
    if (!activePipeline || !inputFile) return
    // Convert pipeline steps → workflow steps the existing engine understands
    const workflow = buildWorkflow(activePipeline, inputFile, project)
    setRunState({ status: 'running', stepId: null, log: [] })
    onRunPipeline?.(workflow)
  }

  // ── Export / Import ───────────────────────────────────────────────────────
  function exportPipeline() {
    if (!activePipeline) return
    const blob = new Blob([JSON.stringify(activePipeline, null, 2)], { type: 'application/json' })
    const a = document.createElement('a')
    a.href = URL.createObjectURL(blob)
    a.download = `${activePipeline.name.replace(/\s+/g, '_')}.pipeline.json`
    a.click()
  }

  function importPipeline(e) {
    const file = e.target.files[0]
    if (!file) return
    const reader = new FileReader()
    reader.onload = ev => {
      try {
        const p = JSON.parse(ev.target.result)
        p.id = uid()
        savePipelines([...pipelines, p])
        setActive(p.id)
      } catch { alert('Invalid pipeline file') }
    }
    reader.readAsText(file)
    e.target.value = ''
  }

  return (
    <div className="node-page">

      {/* ── Left: pipeline list ─────────────────────────────────────── */}
      <aside className="node-sidebar">
        <div className="node-sidebar-header">
          <span className="node-sidebar-title">Pipelines</span>
          <button className="node-new-btn" onClick={() => setShowTemplates(true)} title="New pipeline">＋</button>
        </div>

        <div className="node-pipeline-list">
          {pipelines.length === 0 && (
            <div className="node-empty-list">
              <div className="node-empty-icon">⬡</div>
              <div>No pipelines yet</div>
              <button className="node-create-first" onClick={() => setShowTemplates(true)}>
                Create one
              </button>
            </div>
          )}
          {pipelines.map(p => (
            <div
              key={p.id}
              className={`node-pipeline-row ${p.id === activePipelineId ? 'active' : ''}`}
              onClick={() => { setActive(p.id); setSelectedStep(null) }}
            >
              <div className="node-pipeline-row-info">
                <div className="node-pipeline-row-name">{p.name}</div>
                <div className="node-pipeline-row-meta">{p.steps.length} step{p.steps.length !== 1 ? 's' : ''}</div>
              </div>
              <button
                className="node-pipeline-delete"
                onClick={e => { e.stopPropagation(); deletePipeline(p.id) }}
                title="Delete"
              >×</button>
            </div>
          ))}
        </div>

        {/* Import */}
        <label className="node-import-btn" title="Import .pipeline.json">
          ↑ Import
          <input type="file" accept=".json" style={{ display:'none' }} onChange={importPipeline} />
        </label>
      </aside>

      {/* ── Center: pipeline canvas ─────────────────────────────────── */}
      <main className="node-canvas">
        {!activePipeline ? (
          <div className="node-canvas-empty">
            <div className="node-canvas-empty-icon">⬡</div>
            <div className="node-canvas-empty-title">No pipeline selected</div>
            <div className="node-canvas-empty-sub">Create one from the sidebar</div>
          </div>
        ) : (
          <>
            {/* Pipeline header */}
            <div className="node-canvas-header">
              <input
                className="node-pipeline-name-input"
                value={activePipeline.name}
                onChange={e => renamePipeline(activePipeline.id, e.target.value)}
              />
              <div className="node-canvas-header-actions">
                <button className="node-action-btn" onClick={exportPipeline} title="Export pipeline">↓ Export</button>
              </div>
            </div>

            {/* Input file row */}
            <div className="node-input-row">
              <div className="node-input-label">INPUT FILE</div>
              <button className="node-input-pick" onClick={pickInputFile}>
                {inputFile ? inputFile.split(/[\\/]/).pop() : 'Choose file…'}
              </button>
              {inputFile && (
                <button className="node-input-clear" onClick={() => setInputFile(null)}>×</button>
              )}
            </div>

            {/* Steps */}
            <div className="node-steps">
              {activePipeline.steps.length === 0 && (
                <div className="node-steps-empty">
                  Add steps from the panel on the right →
                </div>
              )}

              {activePipeline.steps.map((step, idx) => (
                <React.Fragment key={step.id}>
                  <div
                    className={`node-step ${selectedStepId === step.id ? 'selected' : ''}`}
                    onClick={() => setSelectedStep(step.id)}
                    draggable
                    onDragStart={e => onDragStart(e, idx)}
                    onDragEnter={e => onDragEnter(e, idx)}
                    onDragEnd={onDragEnd}
                    onDragOver={e => e.preventDefault()}
                  >
                    {/* Step number */}
                    <div className="node-step-num" style={{ background: stepColor(step.type) }}>
                      {idx + 1}
                    </div>

                    {/* Step body */}
                    <div className="node-step-body">
                      <div className="node-step-top">
                        <span className="node-step-icon">{stepIcon(step.type)}</span>
                        <span className="node-step-title">{step.title}</span>
                        <span className="node-step-type-badge" style={{ borderColor: stepColor(step.type), color: stepColor(step.type) }}>
                          {stepLabel(step.type)}
                        </span>
                      </div>

                      {/* Preview of key config */}
                      <div className="node-step-preview">
                        {step.type === 'shell' || step.type === 'for_each_shell' || step.type === 'scale_916' ? (
                          <code>{(step.command || STEP_TYPES[step.type]?.defaultCommand || '').slice(0, 80)}…</code>
                        ) : step.type === 'whisper' ? (
                          <span>model: {step.model} · {step.wordsPerLine} words/line · {step.outputFormat}</span>
                        ) : step.type === 'ai_analyse' ? (
                          <span className="node-step-prompt-preview">{(step.prompt || '').slice(0, 70)}…</span>
                        ) : step.type === 'ffmpeg_clip' ? (
                          <span>Clips from AI analysis JSON → individual segments</span>
                        ) : step.type === 'burn_captions' ? (
                          <span>fontsize: {step.fontsize} · color: {step.fontcolor}</span>
                        ) : null}
                      </div>
                    </div>

                    {/* Run status indicator */}
                    {runState?.stepId === step.id && (
                      <div className="node-step-running-dot" />
                    )}

                    {/* Remove */}
                    <button
                      className="node-step-remove"
                      onClick={e => { e.stopPropagation(); removeStep(step.id) }}
                      title="Remove step"
                    >×</button>
                  </div>

                  {/* Connector arrow between steps */}
                  {idx < activePipeline.steps.length - 1 && (
                    <div className="node-connector">
                      <div className="node-connector-line" style={{ background: stepColor(step.type) }} />
                      <div className="node-connector-arrow" style={{ borderTopColor: stepColor(activePipeline.steps[idx+1].type) }}>▼</div>
                      <div className="node-connector-label">
                        output → input
                      </div>
                    </div>
                  )}
                </React.Fragment>
              ))}
            </div>

            {/* Run bar */}
            <div className="node-run-bar">
              <div className="node-run-info">
                {inputFile
                  ? <span className="node-run-file">▶ {inputFile.split(/[\\/]/).pop()}</span>
                  : <span className="node-run-hint">Pick an input file to run</span>
                }
              </div>
              <button
                className={`node-run-btn ${!inputFile ? 'disabled' : ''}`}
                onClick={runPipeline}
                disabled={!inputFile || activePipeline.steps.length === 0}
              >
                Run Pipeline
              </button>
            </div>
          </>
        )}
      </main>

      {/* ── Right: step editor / add panel ─────────────────────────── */}
      <aside className="node-editor">
        {selectedStep ? (
          <StepEditor
            step={selectedStep}
            onUpdate={patch => updateStep(selectedStep.id, patch)}
            onClose={() => setSelectedStep(null)}
          />
        ) : (
          <AddStepPanel onAdd={addStep} />
        )}
      </aside>

      {/* ── Template picker modal ───────────────────────────────────── */}
      {showTemplates && (
        <TemplateModal
          onSelect={createFromTemplate}
          onClose={() => setShowTemplates(false)}
        />
      )}
    </div>
  )
}

// ── Step editor panel ─────────────────────────────────────────────────────────
