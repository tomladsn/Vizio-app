// ── Workflow compiler ─────────────────────────────────────────────────────────
// Converts pipeline JSON → the workflow object your existing runWorkflow IPC expects
export function buildWorkflow(pipeline, inputFile, project) {
  const outputDir = project
    ? `${project.folderPath}\\output`
    : 'output'
  const basename = inputFile.split(/[\\/]/).pop().replace(/\.[^.]+$/, '')

  const resolve = (str, extra = {}) =>
    (str || '')
      .replace(/\{input\}/g,     inputFile)
      .replace(/\{output\}/g,    `${outputDir}\\${basename}_step_${extra.stepNum ?? ''}.${extra.ext ?? 'mp4'}`)
      .replace(/\{outputDir\}/g, outputDir)
      .replace(/\{basename\}/g,  basename)
      .replace(/\{original\}/g,  inputFile)

  const steps = pipeline.steps.map((step, idx) => {
    const num = idx + 1
    const ext = step.outputFormat ?? 'mp4'

    if (step.type === 'shell' || step.type === 'for_each_shell' || step.type === 'scale_916') {
      return {
        id: num, type: 'shell',
        title: step.title,
        description: step.title,
        command: resolve(step.command || STEP_TYPES[step.type].defaultCommand, { stepNum: num, ext }),
        durationSec: null,
      }
    }

    if (step.type === 'whisper') {
      const cmd = `whisper "${inputFile}" --model ${step.model} --output_format ${step.outputFormat} --word_timestamps True --max_words_per_line ${step.wordsPerLine} --output_dir "${outputDir}"`
      return { id: num, type: 'shell', title: step.title, description: step.title, command: cmd, durationSec: null }
    }

    if (step.type === 'ai_analyse') {
      // Write a special shell step that will be intercepted by the pipeline runner
      return { id: num, type: 'ai_analyse', title: step.title, prompt: step.prompt, outputFormat: step.outputFormat }
    }

    if (step.type === 'ffmpeg_clip') {
      return { id: num, type: 'ffmpeg_clip', title: step.title, sourceVideo: inputFile }
    }

    if (step.type === 'burn_captions') {
      return {
        id: num, type: 'shell',
        title: step.title,
        command: `ffmpeg -y -i "${outputDir}\\clip_{n}.mp4" -vf "subtitles=${outputDir}\\clip_{n}.srt:force_style='FontSize=${step.fontsize},PrimaryColour=&Hffffff&'" "${outputDir}\\clip_{n}_captioned.mp4"`,
        durationSec: null,
      }
    }

    return { id: num, type: 'shell', title: step.title, command: '', durationSec: null }
  })

  return {
    message: pipeline.name,
    steps,
    final_output: `${outputDir}\\${basename}_final.mp4`,
  }
}
